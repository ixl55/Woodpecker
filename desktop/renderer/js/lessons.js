const all = (from, list) => list.split(' ').map((to) => [from, to]);
const ray = (a, b) => {
  const files = 'abcdefgh';
  const [f1, r1, f2, r2] = [files.indexOf(a[0]), +a[1], files.indexOf(b[0]), +b[1]];
  const n = Math.max(Math.abs(f2 - f1), Math.abs(r2 - r1));
  return Array.from({ length: n + 1 }, (_, i) =>
    files[f1 + (Math.sign(f2 - f1) * i)] + (r1 + Math.sign(r2 - r1) * i));
};

