// The Learn curriculum: units -> lessons -> steps. Data only; learn.js plays it and learn-rules.js checks it.
// Every goal has a reference `solution`, every star course a `par`, and test/lessons.test.js proves both
// on the board, so no exercise can be unsolvable or accept a wrong idea.
//
// Step types
//   show     text + position, with optional arrows [[from, to]] and marked squares
//   squares  click the named squares in turn: targets [[square | 'a|b', prompt], ...]
//   stars    move freely (the other side never moves) to collect every star in `par` moves;
//            captureAll: also take every enemy piece; guarded: never stop on an attacked square
//   goal     one move that passes `goal` (see TESTS in learn-rules.js)
//   line     play the given moves; the replies are automatic; a different mate on the last move counts
//   play     mate the lone king against the practice opponent within `limit` moves
//   quiz     pick the right answer; `verify` lets the tests check it on the board
